#!/usr/bin/env python3
"""Builds BangBar/KeyboardImpossibleLetters-<language>.txt for the automatic layout switcher.

A letter pair or triple (with ^ / $ marking the word's start / end) is impossible when it never occurs in a
large word list. Every combination that does occur in the running-text corpus is then dropped again, because
word lists miss inflected forms (Russian Hunspell stems) and some spellings (ё written as е).

Sources used for the committed tables:
  en words:  /usr/share/dict/web2, web2a, words (public domain, ship with macOS)
  ru words:  ru_RU.dic from hunspell-ru (Lebedev, BSD-style), converted from KOI8-R, affix flags stripped
  corpus:    plain-text intros of random Wikipedia articles (~30k English words, ~58k Russian words)

Usage:
  build_keyboard_letter_patterns.py en OUT --words web2 web2a words --corpus en.txt
  build_keyboard_letter_patterns.py ru OUT --words ru_words.txt --corpus ru.txt
"""

import argparse
import re

ALPHABETS = {
    "en": "abcdefghijklmnopqrstuvwxyz",
    "ru": "абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
}


def grams(words, alphabet):
    seen = set()
    for word in words:
        if not word or any(c not in alphabet for c in word):
            continue
        marked = "^" + word + "$"
        for size in (2, 3):
            for i in range(len(marked) - size + 1):
                seen.add(marked[i:i + size])
    return seen


def read_words(paths):
    for path in paths:
        with open(path, encoding="utf-8") as file:
            for line in file:
                for word in re.split(r"[\s\-/]+", line.strip().lower()):
                    yield word


def read_corpus(paths):
    for path in paths:
        with open(path, encoding="utf-8") as file:
            yield from re.findall(r"[^\W\d_]+", file.read().lower())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("language", choices=ALPHABETS)
    parser.add_argument("output")
    parser.add_argument("--words", nargs="+", required=True)
    parser.add_argument("--corpus", nargs="+", required=True)
    args = parser.parse_args()

    alphabet = ALPHABETS[args.language]
    seen = grams(read_words(args.words), alphabet)
    seen_in_text = grams(read_corpus(args.corpus), alphabet)
    starts, ends = "^" + alphabet, alphabet + "$"

    def keep(gram):
        # Word lists write ё as е too often to call anything with ё impossible.
        return gram not in seen and gram not in seen_in_text and "ё" not in gram

    pairs = [a + b for a in starts for b in ends if a + b != "^$" and keep(a + b)]
    # A triple whose own pairs are impossible adds nothing: the pair already counts.
    triples = [
        a + b + c for a in starts for b in alphabet for c in ends
        if a + b in seen and b + c in seen and keep(a + b + c)
    ]

    with open(args.output, "w", encoding="utf-8") as out:
        out.write(f"# Letter pairs and triples that never occur in {args.language} words; ^ and $ mark word edges.\n")
        out.write("# Generated by scripts/build_keyboard_letter_patterns.py — do not edit by hand.\n")
        for first in starts:
            line = [gram for gram in pairs + triples if gram[0] == first]
            if line:
                out.write(" ".join(line) + "\n")
    print(f"{args.language}: {len(pairs)} pairs, {len(triples)} triples → {args.output}")


if __name__ == "__main__":
    main()
